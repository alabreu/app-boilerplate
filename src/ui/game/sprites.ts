/** Fonte 3×5 para números e poucos símbolos desenhados dentro do canvas. */
export const FONT: Record<string, string[]> = {
  '0': ['111', '101', '101', '101', '111'],
  '1': ['010', '110', '010', '010', '111'],
  '2': ['111', '001', '111', '100', '111'],
  '3': ['111', '001', '111', '001', '111'],
  '4': ['101', '101', '111', '001', '001'],
  '5': ['111', '100', '111', '001', '111'],
  '6': ['111', '100', '111', '101', '111'],
  '7': ['111', '001', '001', '010', '010'],
  '8': ['111', '101', '111', '101', '111'],
  '9': ['111', '101', '111', '001', '111'],
  '+': ['000', '010', '111', '010', '000'],
  '-': ['000', '000', '111', '000', '000'],
  x: ['000', '101', '010', '101', '000'],
  N: ['101', '111', '111', '111', '101'],
  V: ['101', '101', '101', '101', '010'],
  '!': ['010', '010', '010', '000', '010'],
  '?': ['111', '001', '011', '000', '010'],
  ' ': ['000', '000', '000', '000', '000'],
}

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  outline = '#121018',
): void {
  const w = text.length * 4 - 1
  let cx = Math.round(x - w / 2)
  const cy = Math.round(y)
  // Contorno: o mesmo texto deslocado nas 4 direções.
  for (const [ox, oy] of [
    [1, 0],
    [-1, 0],
    [0, 1],
    [0, -1],
  ]) {
    drawGlyphs(ctx, text, cx + ox, cy + oy, outline)
  }
  drawGlyphs(ctx, text, cx, cy, color)
  cx += w
}

function drawGlyphs(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
) {
  ctx.fillStyle = color
  let cx = x
  for (const ch of text) {
    const g = FONT[ch] ?? FONT[' ']
    for (let r = 0; r < 5; r++) {
      for (let c = 0; c < 3; c++) {
        if (g[r][c] === '1') ctx.fillRect(cx + c, y + r, 1, 1)
      }
    }
    cx += 4
  }
}
