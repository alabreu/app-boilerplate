import { PAL } from './palette'

/**
 * Sprites como texto: cada linha é uma fileira de pixels, cada letra uma cor
 * da paleta (`.` = transparente). Rasterizados uma vez em canvases pequenos
 * e desenhados com drawImage sem suavização.
 */
export type Spr = HTMLCanvasElement

const cache = new Map<string, Spr>()

export function rasterize(
  rows: string[],
  key?: string,
  remap?: Record<string, string>,
): Spr {
  const k = key ?? rows.join('|') + JSON.stringify(remap ?? {})
  const hit = cache.get(k)
  if (hit) return hit
  const h = rows.length
  const w = Math.max(...rows.map((r) => r.length))
  const c = document.createElement('canvas')
  c.width = w
  c.height = h
  const ctx = c.getContext('2d')!
  for (let y = 0; y < h; y++) {
    const row = rows[y]
    for (let x = 0; x < row.length; x++) {
      let ch = row[x]
      if (ch === '.') continue
      if (remap && remap[ch]) ch = remap[ch]
      const color = PAL[ch]
      if (!color) continue
      ctx.fillStyle = color
      ctx.fillRect(x, y, 1, 1)
    }
  }
  cache.set(k, c)
  return c
}

